def m(value_mm: float) -> float:
    return value_mm * MM


def connect_solidworks():
    try:
        sw = win32com.client.Dispatch("SldWorks.Application")
    except Exception as exc:  # pragma: no cover - depends on local COM state
        raise RuntimeError(
            "Could not connect to SolidWorks through COM. Open SolidWorks once "
            "and rerun this script."
        ) from exc
    sw.Visible = True
    return sw


def ensure_dirs(clean: bool = True) -> None:
    if clean and PROJECT_DIR.exists():
        # This directory is generated by this script; remove only this exact path.
        shutil.rmtree(PROJECT_DIR)
    PARTS_DIR.mkdir(parents=True, exist_ok=True)
    ASSEMBLY_DIR.mkdir(parents=True, exist_ok=True)
    EXPORT_DIR.mkdir(parents=True, exist_ok=True)


def new_part(sw):
    template = sw.GetUserPreferenceStringValue(8)
    model = sw.NewDocument(template, 0, 0, 0)
    if model is None:
        model = sw.ActiveDoc
    return model


def new_assembly(sw):
    template = sw.GetUserPreferenceStringValue(9)
    model = sw.NewDocument(template, 0, 0, 0)
    if model is None:
        model = sw.ActiveDoc
    return model


def save_model(model, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    model.SaveAs3(str(path), SW_SAVE_CURRENT_VERSION, SW_SAVE_SILENT)
    if not path.exists():
        raise RuntimeError(f"SolidWorks failed to save {path}")


def save_as_if_possible(model, path: Path) -> bool:
    try:
        model.SaveAs3(str(path), SW_SAVE_CURRENT_VERSION, SW_SAVE_SILENT)
        return path.exists()
    except Exception:
        return False


def color_feature(feature, color: Color) -> None:
    feature.SetMaterialPropertyValues2(color.as_variant(), SW_THIS_CONFIGURATION, "")


def rename_feature(feature, name: str):
    if feature is not None:
        feature.Name = name
    return feature


def select_plane(model, plane_name: str) -> None:
    model.ClearSelection2(True)
    if not model.SelectByID(plane_name, "PLANE", 0, 0, 0):
        raise RuntimeError(f"Could not select plane: {plane_name}")


def extrude(model, depth_mm: float, start_offset_mm: float = 0.0, merge: bool = True):
    return model.FeatureManager.FeatureExtrusion2(
        True,
        False,
        False,
        SW_END_BLIND,
        SW_END_BLIND,
        m(depth_mm),
        0.0,
        False,
        False,
        False,
        False,
        0.0,
        0.0,
        False,
        False,
        False,
        False,
        merge,
        True,
        True,
        SW_START_OFFSET if abs(start_offset_mm) > 1e-9 else SW_START_SKETCH_PLANE,
        m(start_offset_mm),
        False,
    )


def add_box(
    model,
    name: str,
    center_mm: tuple[float, float, float],
    size_mm: tuple[float, float, float],
    color: Color,
    merge: bool = True,
):
    cx, cy, cz = center_mm
    sx, sy, sz = size_mm
    select_plane(model, FRONT_PLANE)
    sk = model.SketchManager
    sk.InsertSketch(True)
    sk.CreateCenterRectangle(m(cx), m(cy), 0.0, m(cx + sx / 2), m(cy + sy / 2), 0.0)
    sk.InsertSketch(True)
    feature = extrude(model, sz, cz - sz / 2, merge)
    rename_feature(feature, name)
    color_feature(feature, color)
    return feature


def add_cylinder_z(
    model,
    name: str,
    center_mm: tuple[float, float, float],
    diameter_mm: float,
    height_mm: float,
    color: Color,
    merge: bool = True,
):
    cx, cy, cz = center_mm
    select_plane(model, FRONT_PLANE)
    sk = model.SketchManager
    sk.InsertSketch(True)
    model.CreateCircleByRadius2(m(cx), m(cy), 0.0, m(diameter_mm / 2))
    sk.InsertSketch(True)
    feature = extrude(model, height_mm, cz - height_mm / 2, merge)
    rename_feature(feature, name)
    color_feature(feature, color)
    return feature


def add_cylinder_y(
    model,
    name: str,
    center_mm: tuple[float, float, float],
    diameter_mm: float,
    depth_mm: float,
    color: Color,
    merge: bool = True,
):
    cx, cy, cz = center_mm
    select_plane(model, TOP_PLANE)
    sk = model.SketchManager
    sk.InsertSketch(True)
    model.CreateCircleByRadius2(m(cx), 0.0, m(cz), m(diameter_mm / 2))
    sk.InsertSketch(True)
    feature = extrude(model, depth_mm, cy - depth_mm / 2, merge)
    rename_feature(feature, name)
    color_feature(feature, color)
    return feature



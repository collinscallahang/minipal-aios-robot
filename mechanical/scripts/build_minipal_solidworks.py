"""Build the MiniPal SolidWorks model set.

The script creates a small SolidWorks project under
``mechanical/solidworks_minipal``:

- individual simplified SLDPRT files for the shell and each module
- sub-assemblies for the electronics and actuator groups
- one top-level assembly that integrates the complete desk robot
- a STEP export of the final assembly, when the local SolidWorks export
  options allow it

Coordinates are in millimeters in the layout dictionaries and converted to
meters for the SolidWorks API.
"""


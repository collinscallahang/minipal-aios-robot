@dataclass(frozen=True)
class Color:
    r: float
    g: float
    b: float
    ambient: float = 0.45
    diffuse: float = 0.85
    specular: float = 0.25
    shininess: float = 0.25
    transparency: float = 0.0
    emission: float = 0.0

    def as_variant(self) -> VARIANT:
        values = [
            self.r,
            self.g,
            self.b,
            self.ambient,
            self.diffuse,
            self.specular,
            self.shininess,
            self.transparency,
            self.emission,
        ]
        return VARIANT(pythoncom.VT_ARRAY | pythoncom.VT_R8, values)



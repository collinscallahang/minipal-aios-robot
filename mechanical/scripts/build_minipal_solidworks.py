def close_doc(sw, path: Path) -> None:
    try:
        sw.CloseDoc(path.name)
    except Exception:
        pass


def open_doc(sw, path: Path, doc_type: int):
    return sw.OpenDoc(str(path), doc_type)


def activate_doc(sw, path: Path, doc_type: int):
    doc = None
    try:
        doc = sw.ActivateDoc(path.name)
    except Exception:
        pass
    if doc is None:
        doc = open_doc(sw, path, doc_type)
    return sw.ActiveDoc if sw.ActiveDoc is not None else doc


def create_assembly(sw, name: str, components: Iterable[tuple[Path, tuple[float, float, float]]]) -> Path:
    model = new_assembly(sw)
    asm = model
    assembly_title = model.GetTitle
    for path, pos_mm in components:
        doc_type = SW_DOC_PART if path.suffix.lower() == ".sldprt" else SW_DOC_ASSEMBLY
        open_doc(sw, path, doc_type)
        sw.ActivateDoc(assembly_title)
        x, y, z = pos_mm
        comp = asm.AddComponent5(
            str(path),
            SW_ADD_CURRENT_SELECTED_CONFIG,
            "",
            False,
            "",
            m(x),
            m(y),
            m(z),
        )
        if comp is None:
            raise RuntimeError(f"Failed to add component: {path}")
    try:
        model.ShowNamedView2("*Isometric", 7)
    except Exception:
        pass
    model.ViewZoomtofit2()
    path = ASSEMBLY_DIR / f"{name}.SLDASM"
    save_model(model, path)
    return path


def export_png_view(model, path: Path, view_name: str, view_id: int) -> Path | None:
    try:
        model.ShowNamedView2(view_name, view_id)
    except Exception:
        pass
    try:
        model.ViewZoomtofit2()
    except Exception:
        pass
    if save_as_if_possible(model, path):
        return path
    return None



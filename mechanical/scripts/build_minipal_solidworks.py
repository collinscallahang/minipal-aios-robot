def main() -> int:
    assemble_only = "--assemble-only" in sys.argv
    appearance_only = "--appearance-only" in sys.argv
    sw = connect_solidworks()

    # Remove temporary scratch documents created while testing the automation,
    # but keep SolidWorks open for the final result.
    try:
        sw.CloseAllDocuments(True)
    except Exception:
        pass

    ensure_dirs(clean=not assemble_only and not appearance_only)

    part_paths = {
        "shell": PARTS_DIR / "MiniPal_case_shell.SLDPRT",
        "sensor": PARTS_DIR / "MiniPal_HC_SR04_sensor.SLDPRT",
        "servo": PARTS_DIR / "MiniPal_SG90_servo.SLDPRT",
        "esp32": PARTS_DIR / "MiniPal_ESP32_devkit.SLDPRT",
        "power": PARTS_DIR / "MiniPal_5V_power_pack.SLDPRT",
        "button": PARTS_DIR / "MiniPal_top_button.SLDPRT",
        "led": PARTS_DIR / "MiniPal_WS2812_LED.SLDPRT",
        "buzzer": PARTS_DIR / "MiniPal_buzzer.SLDPRT",
        "labels": PARTS_DIR / "MiniPal_dimension_markers.SLDPRT",
        "case_details": PARTS_DIR / "MiniPal_case_details_feet_trim.SLDPRT",
        "sim_robot": PARTS_DIR / "MiniPal_simulation_style_robot.SLDPRT",
        "wires": PARTS_DIR / "MiniPal_wire_harness_and_ports.SLDPRT",
    }

    if assemble_only or appearance_only:
        missing = [str(path) for path in part_paths.values() if not path.exists()]
        if missing:
            raise FileNotFoundError("Missing part files for --assemble-only:\n" + "\n".join(missing))
    else:
        creators = {
            "shell": create_shell_part,
            "sensor": create_hcsr04_part,
            "servo": create_servo_part,
            "esp32": create_esp32_part,
            "power": create_power_part,
            "button": create_button_part,
            "led": create_led_part,
            "buzzer": create_buzzer_part,
            "labels": create_label_part,
            "case_details": create_case_details_part,
            "sim_robot": create_sim_robot_appearance_part,
            "wires": create_wire_harness_part,
        }
        for key, creator in creators.items():
            part_paths[key] = creator(sw)
        for path in part_paths.values():
            close_doc(sw, path)

    if appearance_only:
        top = create_assembly(
            sw,
            "MiniPal_main_assembly",
            [
                (part_paths["sim_robot"], (0, 0, 0)),
            ],
        )
        top_model = activate_doc(sw, top, SW_DOC_ASSEMBLY)
        exports: dict[str, Path | None] = {
            "STEP": None,
            "PNG preview - isometric": None,
            "PNG preview - front": None,
            "PNG preview - top layout": None,
        }
        iso_png = export_png_view(top_model, EXPORT_DIR / "MiniPal_main_assembly_isometric.png", "*Isometric", 7)
        if iso_png:
            exports["PNG preview - isometric"] = iso_png
        front_png = export_png_view(top_model, EXPORT_DIR / "MiniPal_main_assembly_front.png", "*Front", 1)
        if front_png:
            exports["PNG preview - front"] = front_png
        top_png = export_png_view(top_model, EXPORT_DIR / "MiniPal_main_assembly_top_layout.png", "*Top", 5)
        if top_png:
            exports["PNG preview - top layout"] = top_png
        step_path = EXPORT_DIR / "MiniPal_main_assembly.step"
        top_model = activate_doc(sw, top, SW_DOC_ASSEMBLY)
        if save_as_if_possible(top_model, step_path):
            exports["STEP"] = step_path
        write_finished_readme(top, part_paths["sim_robot"], exports)
        print(f"Created MiniPal finished SolidWorks model: {PROJECT_DIR}")
        print(f"Top assembly: {top}")
        if exports["STEP"]:
            print(f"STEP export: {exports['STEP']}")
        if exports["PNG preview - isometric"]:
            print(f"PNG preview: {exports['PNG preview - isometric']}")
        return 0

    electronics = create_assembly(
        sw,
        "MiniPal_electronics_subassembly",
        [
            (part_paths["esp32"], (0, 6, 25)),
            (part_paths["power"], (0, 6, 11)),
            (part_paths["sensor"], (0, -48.5, 37)),
            (part_paths["led"], (-30, -18, 36)),
            (part_paths["buzzer"], (31, -18, 32)),
            (part_paths["wires"], (0, 0, 0)),
        ],
    )
    close_doc(sw, electronics)

    motion = create_assembly(
        sw,
        "MiniPal_motion_subassembly",
        [
            (part_paths["servo"], (0, 0, 51)),
            (part_paths["button"], (0, 0, 73)),
        ],
    )
    close_doc(sw, motion)

    module_layout = create_assembly(
        sw,
        "MiniPal_internal_module_layout_assembly",
        [
            (part_paths["shell"], (0, 0, 35)),
            (part_paths["case_details"], (0, 0, 0)),
            (electronics, (0, 0, 0)),
            (motion, (0, 0, 0)),
            (part_paths["labels"], (0, 0, 0)),
        ],
    )
    close_doc(sw, module_layout)

    top = create_assembly(
        sw,
        "MiniPal_main_assembly",
        [
            (part_paths["sim_robot"], (0, 0, 0)),
        ],
    )

    exports: dict[str, Path | None] = {
        "STEP": None,
        "PNG preview - isometric": None,
        "PNG preview - front": None,
        "PNG preview - top layout": None,
    }
    top_model = activate_doc(sw, top, SW_DOC_ASSEMBLY)
    iso_png = export_png_view(top_model, EXPORT_DIR / "MiniPal_main_assembly_isometric.png", "*Isometric", 7)
    if iso_png:
        exports["PNG preview - isometric"] = iso_png
    front_png = export_png_view(top_model, EXPORT_DIR / "MiniPal_main_assembly_front.png", "*Front", 1)
    if front_png:
        exports["PNG preview - front"] = front_png
    top_png = export_png_view(top_model, EXPORT_DIR / "MiniPal_main_assembly_top_layout.png", "*Top", 5)
    if top_png:
        exports["PNG preview - top layout"] = top_png

    step_path = EXPORT_DIR / "MiniPal_main_assembly.step"
    top_model = activate_doc(sw, top, SW_DOC_ASSEMBLY)
    if save_as_if_possible(top_model, step_path):
        exports["STEP"] = step_path

    exploded = create_assembly(
        sw,
        "MiniPal_exploded_layout_assembly",
        [
            (part_paths["shell"], (0, 0, 35)),
            (part_paths["case_details"], (0, 0, 0)),
            (electronics, (135, 0, 0)),
            (motion, (-105, 0, 0)),
            (part_paths["labels"], (0, 0, 0)),
        ],
    )
    exploded_model = activate_doc(sw, exploded, SW_DOC_ASSEMBLY)
    exploded_png = export_png_view(
        exploded_model,
        EXPORT_DIR / "MiniPal_exploded_layout_isometric.png",
        "*Isometric",
        7,
    )
    if exploded_png:
        exports["PNG preview - exploded layout"] = exploded_png

    try:
        top_model = activate_doc(sw, top, SW_DOC_ASSEMBLY)
        top_model.ShowNamedView2("*Isometric", 7)
        top_model.ViewZoomtofit2()
    except Exception:
        pass

    paths = {
        "top_assembly": top,
        "module_layout_assembly": module_layout,
        "exploded_assembly": exploded,
        "electronics_assembly": electronics,
        "motion_assembly": motion,
    }
    write_readme(paths, exports)

    print(f"Created MiniPal SolidWorks project: {PROJECT_DIR}")
    print(f"Top assembly: {top}")
    if exports["STEP"]:
        print(f"STEP export: {exports['STEP']}")
    if exports["PNG preview - isometric"]:
        print(f"PNG preview: {exports['PNG preview - isometric']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
